CREATE TABLE IF NOT EXISTS evaluations (
 id VARCHAR(36) PRIMARY KEY, title VARCHAR(100) NOT NULL,
 pin VARCHAR(6) NOT NULL UNIQUE, state VARCHAR(20) NOT NULL,
 expires_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE IF NOT EXISTS participants (
 id VARCHAR(36) PRIMARY KEY, evaluation_id VARCHAR(36) NOT NULL REFERENCES evaluations(id),
 nickname VARCHAR(20) NOT NULL, token VARCHAR(64) NOT NULL UNIQUE,
 active BOOLEAN NOT NULL, last_seen TIMESTAMP WITH TIME ZONE NOT NULL,
 UNIQUE(evaluation_id, nickname)
);

CREATE TABLE IF NOT EXISTS evaluation_settings (
 evaluation_id VARCHAR(36) PRIMARY KEY REFERENCES evaluations(id),
 ai_policy VARCHAR(20) NOT NULL
);
CREATE TABLE IF NOT EXISTS questions (
 id VARCHAR(36) PRIMARY KEY, evaluation_id VARCHAR(36) NOT NULL REFERENCES evaluations(id),
 position INT NOT NULL, title VARCHAR(200) NOT NULL, content VARCHAR(10000) NOT NULL,
 UNIQUE(evaluation_id, position)
);
CREATE TABLE IF NOT EXISTS answers (
 participant_id VARCHAR(36) NOT NULL REFERENCES participants(id),
 question_id VARCHAR(36) NOT NULL REFERENCES questions(id),
 content VARCHAR(10000) NOT NULL, version INT NOT NULL, updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
 PRIMARY KEY(participant_id, question_id)
);
CREATE TABLE IF NOT EXISTS ai_turns (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 request_id VARCHAR(64) NOT NULL, evaluation_id VARCHAR(36) NOT NULL REFERENCES evaluations(id),
 participant_id VARCHAR(36) NOT NULL REFERENCES participants(id), question_id VARCHAR(36) NOT NULL REFERENCES questions(id),
 question_text VARCHAR(4000) NOT NULL, answer_text CLOB,
 state VARCHAR(20) NOT NULL, error_code VARCHAR(50), provider VARCHAR(30) NOT NULL, model VARCHAR(200) NOT NULL,
 ai_policy VARCHAR(20) NOT NULL, answer_version INT NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL, completed_at TIMESTAMP WITH TIME ZONE,
 UNIQUE(participant_id, request_id)
);
CREATE TABLE IF NOT EXISTS learning_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 evaluation_id VARCHAR(36) NOT NULL REFERENCES evaluations(id), participant_id VARCHAR(36) NOT NULL REFERENCES participants(id),
 question_id VARCHAR(36) REFERENCES questions(id), event_type VARCHAR(40) NOT NULL,
 details CLOB NOT NULL, created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE IF NOT EXISTS submissions (
 participant_id VARCHAR(36) PRIMARY KEY REFERENCES participants(id),
 evaluation_id VARCHAR(36) NOT NULL REFERENCES evaluations(id),
 review_token VARCHAR(64) NOT NULL, snapshot CLOB NOT NULL, submitted_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_turns_participant ON ai_turns(participant_id, id);
CREATE INDEX IF NOT EXISTS idx_events_participant ON learning_events(participant_id, id);
